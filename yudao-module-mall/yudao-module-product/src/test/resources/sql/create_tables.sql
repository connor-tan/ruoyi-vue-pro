    `introduction` varchar(256) NOT NULL COMMENT '商品简介',
    `description` text NOT NULL COMMENT '商品详情',
    `bar_code` varchar(64) NOT NULL COMMENT '条形码',
    `biz_scene` varchar(32) NOT NULL DEFAULT 'NORMAL' COMMENT '业务场景',
